'use strict';
// Uses isolated event data and a disconnected provider. Never sends a message.
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { source: axe } = require('axe-core');
const { startAuditFixture, cookieForContext } = require('./audit-fixture.cjs');
const { prepareCaptureDir, ensureRunTmpDir } = require('./capture-dir.cjs');
const { launchBrowser } = require('./audit-browser.cjs');

(async () => {
  if (!process.env.EVENTOUCH_CAPTURE_ROOT) throw new Error('Set a private capture root');
  const out = prepareCaptureDir(path.join(process.env.EVENTOUCH_CAPTURE_ROOT, 'message-routing-details'));
  process.env.TMPDIR = ensureRunTmpDir(out);
  const f = await startAuditFixture(); let browser;
  try {
    const db = f.harness.database, cookie = f.manager.cookie;
    const read = async () => (await db.query('SELECT payload FROM event_workspaces WHERE event_id=$1', [f.eventId])).rows[0].payload;
    const command = (command, payload, commandId = crypto.randomUUID()) => f.helpers.requestJson(f.harness.baseUrl, `/api/events/${f.eventId}/commands`, { method: 'POST', cookie, body: { commandId, command, payload } });
    const initial = await read(), people = initial.participants.slice(0, 2);
    const imported = await command('participant.import', { rows: Array.from({ length: 12 }, (_, index) => ({ name: `합성 일괄 ${index + 1}`, phone: `0108888${String(index).padStart(4, '0')}`, company: '합성 조직', email: '' })) });
    assert.equal(imported.status, 200, 'synthetic participant import must succeed');
    const extra = imported.json.participants;
    const bootstrap = await f.helpers.requestJson(f.harness.baseUrl, `/api/events/${f.eventId}/bootstrap?messageRecipientReview=1`, { cookie });
    const versions = bootstrap.json.state.recipientReviewVersions, ids = [];
    for (let i = 0; i < 2; i++) {
      const result = await command('message.create-charset-reviewed', { ids: [people[i].id], expectedRecipientVersions: [versions[people[i].id]], channel: 'SMS', title: i ? '합성 그룹 예약' : '합성 참가 상태 예약', body: '합성 예약 안내', simulate: false, scheduled: new Date(Date.now() + 3600000).toISOString(), scheduleMode: 'MANUAL' });
      assert.equal(result.status, 201, JSON.stringify(result.json)); ids.push(result.json.message.id);
    }
    const batch = await command('message.create-charset-reviewed', { ids: extra.map(person => person.id), expectedRecipientVersions: extra.map(person => versions[person.id]), channel: 'SMS', title: '합성 다수 예약', body: '합성 예약 안내', simulate: false, scheduled: new Date(Date.now() + 3600000).toISOString(), scheduleMode: 'MANUAL' });
    assert.equal(batch.status, 201, JSON.stringify(batch.json));
    assert.equal((await command('participant.status', { ids: [people[0].id], status: 'WAITLIST' })).status, 200);
    assert.equal((await command('participant.update', { id: people[0].id, name: '합성 변경 이름' })).status, 200);
    const batchStatus = await command('participant.status', { ids: extra.map(person => person.id), status: 'WAITLIST' });
    assert.equal(batchStatus.status, 200, JSON.stringify(batchStatus.json));
    const group = initial.groups.find(value => value !== people[1].group); assert.ok(group);
    assert.equal((await command('group.assign', { ids: [people[1].id], group })).status, 200);
    const ws = await read();
    for (const message of ws.messages.filter(item => ids.includes(item.id))) message.scheduled = new Date(Date.now() - 60000).toISOString();
    const old = structuredClone(ws.messages.find(item => item.id === ids[1]));
    old.id = 'synthetic-legacy-reservation'; old.title = '합성 이전 예약'; old.scheduled = new Date(Date.now() + 3600000).toISOString(); old.scheduleMode = 'AUTO'; old.autoScheduleIntent = 'confirmed-v1';
    delete old.recipientRoutingReviewVersion; delete old.recipientSnapshot[0].routingVersion; ws.messages.unshift(old);
    const hashOnly = structuredClone(ws.messages.find(item => item.id === ids[1]));
    hashOnly.id = 'synthetic-hash-only'; hashOnly.title = '합성 이전 비교 기록';
    delete hashOnly.recipientSnapshot[0].routingStatus; delete hashOnly.recipientSnapshot[0].routingGroup; ws.messages.unshift(hashOnly);
    const longId = 'a'.repeat(128), longRecord = structuredClone(hashOnly);
    longRecord.id = longId; longRecord.title = '합성 긴 식별 예약'; ws.messages.unshift(longRecord);
    await db.query('UPDATE event_workspaces SET payload=$2::jsonb WHERE event_id=$1', [f.eventId, JSON.stringify(ws)]);
    const refreshed = await f.helpers.requestJson(f.harness.baseUrl, `/api/events/${f.eventId}/bootstrap?messageRecipientReview=1`, { cookie });
    for (const id of ids) assert.equal(refreshed.json.state.messageSchedule.blocked.find(item => item.id === id)?.reason, 'RECIPIENT_CHANGED');
    assert.ok(!JSON.stringify(refreshed.json.state.messageSchedule.blocked).includes('changeDetails'), 'the initial message list does not preload per-person details');
    const detailed = await f.helpers.requestJson(f.harness.baseUrl, `/api/events/${f.eventId}/bootstrap?messageRecipientReview=1&messageChangeId=${encodeURIComponent(ids[0])}`, { cookie });
    const statusDetails = detailed.json.state.messageChangeReview.details;
    assert.equal(statusDetails.available, true); assert.deepEqual(statusDetails.changes[0].reasons, ['status']);
    assert.equal(statusDetails.changes[0].beforeStatus, 'APPROVED'); assert.equal(statusDetails.changes[0].afterStatus, 'WAITLIST');
    assert.ok(!JSON.stringify(statusDetails).includes(people[0].phone), 'change details contain only masked contact information');
    const longDetail = await f.helpers.requestJson(f.harness.baseUrl, `/api/events/${f.eventId}/bootstrap?messageRecipientReview=1&messageChangeId=${longId}`, { cookie });
    assert.equal(longDetail.json.state.messageChangeReview.status, 'changed', 'all valid 128-character command IDs remain reviewable');
    assert.deepEqual(await read(), ws, 'reading change details does not mutate the event');
    const summary = await f.helpers.requestJson(f.harness.baseUrl, `/api/events/${f.eventId}/bootstrap?messageAttentionSummary=1`, { cookie });
    assert.equal(summary.json.state.messageAttentionSummary.blocked, true, 'the message menu shows that a reservation needs attention');
    assert.ok(!JSON.stringify(summary.json).includes('changeDetails'), 'menu summary does not expose individual change details');
    const staff = await f.helpers.requestJson(f.harness.baseUrl, `/api/events/${f.eventId}/bootstrap?messageRecipientReview=1&messageChangeId=${encodeURIComponent(ids[0])}`, { cookie: f.staff.cookie });
    assert.equal(staff.json.state.messageChangeReview.status, 'unavailable', 'staff projection does not expose message recipient changes');
    const anonymous = await f.helpers.requestJson(f.harness.baseUrl, `/api/events/${f.eventId}/bootstrap?messageRecipientReview=1&messageChangeId=${encodeURIComponent(ids[0])}`);
    assert.equal(anonymous.status, 401, 'anonymous requests cannot inspect changes');
    const outsiderId = `compare-outsider-${crypto.randomUUID()}`;
    await f.helpers.insertAccount(db, { id: outsiderId, role: 'MANAGER', name: '합성 외부 운영자', email: `${outsiderId}@example.test`, orgId: f.helpers.LEGACY_ORG });
    const outsiderCookie = await f.helpers.sessionCookie(f.harness, outsiderId);
    const outsider = await f.helpers.requestJson(f.harness.baseUrl, `/api/events/${f.eventId}/bootstrap?messageRecipientReview=1&messageChangeId=${encodeURIComponent(ids[0])}`, { cookie: outsiderCookie });
    assert.equal(outsider.status, 404, 'an unassigned manager cannot inspect this event');
    const denied = await command('message.retry-charset-reviewed', { id: ids[0] });
    assert.equal(denied.status, 409); assert.equal(denied.json.field, 'recipientChange');
    browser = await launchBrowser(); const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: 'ko-KR', reducedMotion: 'reduce' });
    await context.addCookies([{ ...cookieForContext(f, 'manager'), url: f.baseUrl }]);
    let faults = 2, detailRequests = 0;
    await context.route('**/api/events/*/bootstrap?*', async route => {
      const url = new URL(route.request().url());
      if (!url.searchParams.has('messageChangeId')) return route.continue();
      detailRequests++;
      if (url.searchParams.get('messageChangeId') === ids[0] && faults-- > 0) {
        if (faults === 1) return route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"synthetic"}' });
        const original = await route.fetch();
        return route.fulfill({ response: original, json: { state: {} } });
      }
      return route.continue();
    });
    const page = await context.newPage(); page.setDefaultTimeout(12000);
    await page.goto(`${f.baseUrl}/console/events/${f.eventId}/messages`);
    const statusRow = page.locator('[data-history-row]').filter({ hasText: '합성 참가 상태 예약' });
    const groupRow = page.locator('[data-history-row]').filter({ hasText: '합성 그룹 예약' });
    const oldRow = page.locator('[data-history-row]').filter({ hasText: '합성 이전 예약' });
    await statusRow.getByText('수신자 변경 · 발송 보류').waitFor(); await groupRow.getByText('수신자 변경 · 발송 보류').waitFor();
    assert.equal(detailRequests, 0, 'recipient details load only for an opened campaign');
    await oldRow.getByText('참가 상태·그룹 직접 확인').waitFor();
    assert.equal(await statusRow.getByRole('button', { name: '발송 실행' }).isDisabled(), true);
    await statusRow.getByRole('button', { name: '합성 참가 상태 예약 상세' }).click();
    const detail = page.locator(`#campaign-detail-${ids[0]}`);
    await detail.getByText(/참가 상태·그룹·연락처가 달라졌거나 확인할 수 없습니다/).waitFor();
    for (let index = 0; index < 2; index++) {
      await detail.getByText('변경 내역을 확인하지 못했습니다. 발송은 계속 보류됩니다.').waitFor();
      assert.equal(await statusRow.getByRole('button', { name: '발송 실행' }).isDisabled(), true);
      const retry = await detail.getByRole('button', { name: '변경 내역 다시 확인' }).elementHandle();
      await retry.click();
      await retry.waitForElementState('hidden');
    }
    await detail.getByRole('list', { name: '변경된 수신자 목록' }).getByText(`요청 당시: ${people[0].name}`, { exact: true }).waitFor();
    await detail.getByText('현재 이름: 합성 변경 이름', { exact: true }).waitFor();
    await detail.getByText('참가 상태: 참가 확정 → 대기 명단', { exact: true }).waitFor();
    await page.evaluate(axe);
    for (const width of [320, 390, 1280]) {
      await page.setViewportSize({ width, height: 900 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
      assert.deepEqual(await page.evaluate(async () => (await window.axe.run()).violations.filter(v => ['serious', 'critical'].includes(v.impact)).map(v => v.id)), []);
      await statusRow.scrollIntoViewIfNeeded();
      await page.screenshot({ path: path.join(out, `blocked-${width}.png`), fullPage: true });
      if (width === 390) await detail.screenshot({ path: path.join(out, 'recipient-detail-390.png') });
    }
    await page.setViewportSize({ width: 1280, height: 900 });
    await groupRow.getByRole('button', { name: '합성 그룹 예약 상세' }).click();
    const groupDetail = page.locator(`#campaign-detail-${ids[1]}`);
    await groupDetail.getByText(`그룹: ${people[1].group || '일반'} → ${group}`, { exact: true }).waitFor();
    const hashRow = page.locator('[data-history-row]').filter({ hasText: '합성 이전 비교 기록' });
    await hashRow.getByRole('button', { name: '합성 이전 비교 기록 상세' }).click();
    const hashDetail = page.locator('#campaign-detail-synthetic-hash-only');
    await hashDetail.getByRole('list', { name: '변경된 수신자 목록' }).getByText(people[1].name, { exact: true }).waitFor();
    await hashDetail.getByText('참가 상태 또는 그룹이 변경됐습니다. 이전 값은 확인할 수 없습니다.', { exact: true }).waitFor();
    const batchRow = page.locator('[data-history-row]').filter({ hasText: '합성 다수 예약' });
    await batchRow.getByRole('button', { name: '합성 다수 예약 상세' }).click();
    const batchDetail = page.locator(`#campaign-detail-${batch.json.message.id}`);
    const list = batchDetail.getByRole('list', { name: '변경된 수신자 목록' });
    await list.waitFor();
    assert.equal(await list.getByRole('listitem').count(), 10);
    await batchDetail.getByRole('button', { name: '수신자 더 보기 · 2명 남음' }).click();
    assert.equal(await list.getByRole('listitem').count(), 12, 'all changed people remain reachable');
    await oldRow.getByRole('button', { name: '합성 이전 예약 상세' }).click();
    await page.getByText(/이전 발송 요청은 예약 당시의 참가 상태와 그룹을 확인할 수 없어/).waitFor();
    const oldDetail = page.locator('#campaign-detail-synthetic-legacy-reservation');
    await oldDetail.getByText(/자동 실행 시에도 이 비교 없이 발송될 수 있으므로/).waitFor();
    assert.match(await oldDetail.getByRole('link', { name: '참가자 명단 보기' }).getAttribute('href'), /\/participants$/);
    assert.equal((await command('participant.status', { ids: [people[0].id], status: 'APPROVED' })).status, 200);
    await statusRow.getByRole('button', { name: '합성 참가 상태 예약 상세' }).click();
    await detail.getByText(/최신 명단에서는 변경된 수신자가 없습니다/).waitFor();
    await detail.getByRole('button', { name: '발송 기록 새로고침' }).click();
    await statusRow.getByText('수신자 변경 · 발송 보류').waitFor({ state: 'hidden' });
    assert.equal((await command('participant.status', { ids: [people[0].id], status: 'WAITLIST' })).status, 200);
    await page.getByRole('button', { name: '상태 새로고침' }).click();
    await statusRow.getByText('수신자 변경 · 발송 보류').waitFor();
    await statusRow.getByRole('button', { name: '예약 취소' }).click();
    const confirm = page.getByRole('group', { name: '실행 확인' });
    await confirm.getByRole('button', { name: '예약을 취소한다' }).click();
    await statusRow.getByRole('button', { name: '내용·대상 불러오기' }).waitFor();
    await statusRow.getByRole('button', { name: '내용·대상 불러오기' }).click();
    await page.locator('#campaign-reload-summary').getByText(/선택 1명/).waitFor();
    await page.getByRole('navigation', { name: '메시지 작성 단계' }).getByRole('button', { name: /수신자/ }).waitFor();
    const final = await read();
    assert.equal(final.messages.find(item => item.id === ids[0]).status, 'CANCELLED');
    assert.equal(final.messages.find(item => item.id === ids[1]).status, 'SCHEDULED');
    fs.writeFileSync(path.join(out, 'verification.json'), JSON.stringify({ synthetic: true, noExternalProvider: true, statusAndGroupChangesBlocked: true, oldReservationWarning: true, cancellationAndReview: true, lazyDetails: true, failureAndIncompleteRetry: true, maskedContacts: true, historicalValuesNotInvented: true, permissions: true, multiPersonPaging: true, restoredStateRefresh: true, widths: [320, 390, 1280], physicalDevices: false }, null, 2));
    console.log('message routing details: comparison, access, retry, paging and recovery passed');
  } finally { await browser?.close(); await f.close(); }
})().catch(error => { console.error(String(error?.stack || error).replace(/https?:\/\/[^\s]+/g, '[url redacted]')); process.exitCode = 1; });
